/* Focused regression checks for OCP applicability, units, links, and offline UI. */
const {chromium}=require(process.argv[2]||'playwright');
const fs=require('fs'),path=require('path'),{pathToFileURL}=require('url');
(async()=>{
 const root=__dirname,d=JSON.parse(fs.readFileSync(path.join(root,'content.json'),'utf8'));
 const assert=(v,m)=>{if(!v)throw Error(m);};
 const rules=id=>d.fields.find(f=>f.id===id).rules.filter(r=>r.standard==='ocp');
 const text=id=>rules(id).map(r=>r.expected).join(' ');
 assert(text('MDTS').includes('MDTS=0')&&text('MDTS').includes('262144')&&text('MDTS').includes('최소값은 6'),'MDTS units and zero semantics');
 assert(text('AERL').includes('최소 5'),'AERL raw minimum vs request count');
 assert(text('FRMW').includes('최소 3')&&text('FRMW').includes('read/write'),'Firmware slot count');
 assert(text('PELS').includes('80(50h)'),'PELS 64 KiB units');
 assert(text('WCTEMP').includes('015Eh')&&text('CCTEMP').includes('0166h'),'Temperature constants');
 assert(text('ONCS').includes('무조건 1')&&text('ONCS').includes('A에서는 Write Uncorrectable이 Optional'),'Version and profile scope');
 const lockdown=rules('OACS').filter(r=>r.related_refs.includes('ocp:DP-CFG-11'));
 assert(lockdown.length===2&&lockdown.some(r=>r.profile_scope.includes('A 설정')&&r.expected.includes('bit 10=1'))&&lockdown.some(r=>r.profile_scope.includes('B 설정')&&r.expected.includes('bit 10=0')),'Lockdown A/B requirements');
 assert(rules('PSD31').every(r=>r.field_applicability.includes('NPSS≥31')),'Unused PSD applicability');
 assert(text('NN').includes('NN=1')&&text('NN').includes('7 TiB 경계'),'Factory count and capacity ambiguity');
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const context=await browser.newContext({offline:true,viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[],remote=[];
 page.on('pageerror',e=>errors.push(String(e)));page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
 const url=pathToFileURL(path.join(root,'output/id_ctrl_ko.html')).href;
 await page.goto(url+'#ocp');
 assert(await page.locator('#content h1').innerText()==='OCP 정합성 조건','OCP page route');
 assert(await page.locator('#content').innerText().then(t=>t.includes('항목별')&&t.includes('7 TiB')),'Scope notices');
 await page.screenshot({path:path.join(root,'output/qa/ocp.png')});
 await page.goto(url+'#'+encodeURIComponent('consistency?standard=ocp'));
 assert(await page.locator('#overview-standard').inputValue()==='ocp','OCP deep link filter');
 assert(await page.locator('.check-item').count()===d.ocp_audit.checks,'OCP condition count');
 assert(await page.locator('.check-item[data-standard="nvme"]').count()===0,'NVMe conditions leaked into OCP filter');
 assert(await page.locator('.check-row').count()===d.ocp_audit.fields,'OCP field count');
 await page.locator('#overview-expanded').check();await page.screenshot({path:path.join(root,'output/qa/ocp_conditions.png')});
 await page.locator('#overview-standard').selectOption('nvme');
 assert(await page.locator('.check-item').count()===d.consistency_audit.nvme_checks,'NVMe preserved');
 await page.goto(url+'#'+encodeURIComponent('ocp:DP-CFG-11'));
 assert(await page.locator('#content').innerText().then(t=>t.includes('bit 10=1')&&t.includes('bit 10=0')&&t.includes('OACS')),'Profile source and reverse link');
 const english=page.locator('#content details').first();await english.locator('summary').click();
 assert(await english.innerText().then(t=>t.includes('Lockdown command')),'OCP English source');
 assert(await page.locator('#content a[target="_blank"]').first().getAttribute('href').then(t=>t.includes('OCP2_6.pdf#page=191')),'OCP PDF citation');
 await page.setViewportSize({width:390,height:844});await page.goto(url+'#ocp');
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'OCP mobile clipping');
 await page.screenshot({path:path.join(root,'output/qa/ocp_mobile.png')});
 assert(!errors.length&&!remote.length,'Offline JS/network errors');
 const report={status:'passed',requirements:d.ocp_audit.requirements,cases:d.ocp_audit.cases,fields:d.ocp_audit.fields,checks:d.ocp_audit.checks,nvme_preserved:d.consistency_audit.nvme_checks,offline:true,remote_requests:remote.length,javascript_errors:errors.length};
 fs.writeFileSync(path.join(root,'output/ocp_browser_validation.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
